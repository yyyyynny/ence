/* 저장된 판보다 새 판이면 그 사이에 바뀐 것들을 모아 준다.
   seen이 없으면(첫 방문) 빈 배열 — 처음 온 사람에게 "바뀌었다"고 알릴 것은 없다.
   저장값이 망가져 있어도(옛 형식, 빈 문자열, 목록에 없는 값) 절대 예외를 던지지 않는다.
   여기서 던지면 앱 첫 화면이 통째로 안 뜬다 — 알림 하나 때문에 공부를 못 하게 둘 수는 없다. */
function changesSince(seen){
  if(typeof seen !== 'string' || !seen || seen === APP_VERSION) return [];
  const idx = CHANGELOG.findIndex(c => c.v === seen);
  /* 목록에 없는 값이면(아주 옛 판이거나 손상) 가장 최근 판 것만 보여 준다.
     전부 쏟아내면 처음 보는 사람에게 열 판치 목록이 한 번에 뜬다. */
  const list = idx === -1 ? CHANGELOG.slice(0, 1) : CHANGELOG.slice(0, idx);
  return list.reduce((out, c) => out.concat(c.lines), []);
}
